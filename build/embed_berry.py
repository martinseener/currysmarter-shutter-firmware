#!/usr/bin/env python3
"""embed_berry.py <out.h> - embeds berry/*.be into a C header for xdrv_124_curry_installer.ino.

The version is the driver's VERSION plus a hash of both files, so a firmware
with changed Berry files reinstalls them once."""
import hashlib, pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent
files = {"curry_shutter_be": root / "berry" / "curry_shutter.be", "autoexec_be": root / "berry" / "autoexec.be"}
data = {name: path.read_bytes() for name, path in files.items()}
version = re.search(rb'static VERSION = "([^"]+)"', data["curry_shutter_be"]).group(1).decode()
digest = hashlib.sha256(data["curry_shutter_be"] + data["autoexec_be"]).hexdigest()[:8]

out = ["// generated by build/embed_berry.py - do not edit", "#pragma once",
       '#define CURRY_BERRY_VERSION "%s-%s"' % (version, digest)]
for name, raw in data.items():
    body = ",".join(str(b) for b in raw + b"\0")
    out.append("static const char %s[] PROGMEM = {%s};" % (name, body))
pathlib.Path(sys.argv[1]).write_text("\n".join(out) + "\n")
print("%s-%s" % (version, digest))      # read by build.sh
